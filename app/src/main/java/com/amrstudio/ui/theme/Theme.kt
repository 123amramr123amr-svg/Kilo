enum class ColorSchemeType(val key: String, val name: String) {
    OCEAN("ocean", "Ocean"),
    VIOLET("violet", "Violet"),
    FOREST("forest", "Forest"),
    LIGHT("light", "Light")
}

fun getColorScheme(type: ColorSchemeType, isDark: Boolean) = when (type) {
    ColorSchemeType.OCEAN -> if (isDark) OceanDarkColorScheme else OceanLightColorScheme
    ColorSchemeType.VIOLET -> if (isDark) VioletDarkColorScheme else VioletLightColorScheme
    ColorSchemeType.FOREST -> if (isDark) ForestDarkColorScheme else ForestLightColorScheme
    ColorSchemeType.LIGHT -> if (isDark) LightDarkColorScheme else LightLightColorScheme
}

@Composable
fun AmrStudioTheme(
    colorSchemeType: ColorSchemeType = ColorSchemeType.OCEAN,
    darkTheme: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = getColorScheme(colorSchemeType, darkTheme)
    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}

